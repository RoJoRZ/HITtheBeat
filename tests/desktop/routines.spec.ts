import { test, expect, _electron as electron } from '@playwright/test';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';

test('own routine editor saves independent builds, validates and preserves order', async () => {
  const data = await mkdtemp(path.join(tmpdir(), 'hitthebeat-editor-'));
  const executablePath = process.env.HITTHEBEAT_TEST_EXECUTABLE;
  const launch = () => electron.launch({ executablePath, args: [...(executablePath ? [] : ['.']), `--user-data-dir=${data}`], env: { ...process.env, HITTHEBEAT_DEV: '0' } });
  let app = await launch();
  try {
    let page = await app.firstWindow();
    const errors: string[] = []; page.on('pageerror', reason => errors.push(reason.message));
    await page.evaluate(async () => {
      for (const title of ['Wisselslag', 'Akkoorden']) await window.hitthebeat!.saveExercise({ title, description: '', bpm: 120, detectedBpm: null, analysisStatus: 'unavailable', duration: 60, audio: { name: 'synthetic.mp3', bytes: new Uint8Array([73,68,51,0,0,0,0,0,0,0,0,0]) } });
    });
    await page.getByRole('button', { name: 'Eigen bibliotheek bekijken' }).click();
    await page.getByRole('button', { name: 'Oefenrondje maken', exact: true }).click();
    await page.getByLabel('Naam van het rondje').fill('Warming-up');
    await page.getByLabel('Oefening blok 1').selectOption({ label: 'Wisselslag' });
    await page.getByLabel('BPM oefening 1 stap 1', { exact: true }).fill('60');
    await expect(page.getByTestId('own-round-duration')).toContainText('2:00');
    await page.getByLabel('Fragment oefening 1 stap 1', { exact: true }).selectOption('fragment');
    await page.getByLabel('Begin A oefening 1 stap 1', { exact: true }).fill('12');
    await page.getByLabel('Einde B oefening 1 stap 1', { exact: true }).fill('22');
    await page.getByLabel('Herhalingen oefening 1 stap 1', { exact: true }).fill('2');
    await expect(page.getByTestId('own-round-duration')).toContainText('0:40');
    await page.getByLabel('Einde B oefening 1 stap 1', { exact: true }).fill('11');
    await expect(page.getByRole('alert')).toContainText('fragment');
    await expect(page.getByRole('button', { name: 'Rondje opslaan', exact: true })).toBeDisabled();
    await page.getByLabel('Einde B oefening 1 stap 1', { exact: true }).fill('22');
    await page.getByRole('button', { name: 'Rondje opslaan', exact: true }).click();
    await expect(page.getByRole('status')).toContainText('opgeslagen');
    await page.getByRole('button', { name: 'Oefenrondje maken', exact: true }).click();
    await page.getByLabel('Naam van het rondje').fill('Techniek');
    await page.getByLabel('Oefening blok 1').selectOption({ label: 'Wisselslag' });
    await page.getByLabel('BPM oefening 1 stap 1', { exact: true }).fill('75');
    await page.getByRole('button', { name: 'Stap toevoegen aan oefening 1', exact: true }).click();
    await page.getByLabel('BPM oefening 1 stap 2', { exact: true }).fill('95');
    await page.getByLabel('Herhalingen oefening 1 stap 2', { exact: true }).fill('2');
    await page.getByRole('button', { name: 'Stap toevoegen aan oefening 1', exact: true }).click();
    await page.getByLabel('BPM oefening 1 stap 3', { exact: true }).fill('85');
    await page.getByRole('button', { name: 'Oefening toevoegen aan rondje', exact: true }).click();
    await page.getByLabel('Oefening blok 2').selectOption({ label: 'Akkoorden' });
    await page.getByRole('button', { name: 'Oefening 2 omhoog', exact: true }).click();
    await expect(page.getByLabel('Oefening blok 1')).toHaveValue(await page.getByLabel('Oefening blok 1').locator('option', { hasText: 'Akkoorden' }).getAttribute('value') as string);
    await page.getByRole('button', { name: 'Rondje opslaan', exact: true }).click();
    await expect(page.getByRole('status')).toContainText('opgeslagen');
    await page.setViewportSize({ width: 1440, height: 960 }); await page.locator('h1').click();
    await page.screenshot({ path: 'test-results/phase4-editor.png', fullPage: true });
    await page.getByLabel('BPM oefening 2 stap 1', { exact: true }).fill('80');
    await page.getByRole('button', { name: 'Oefeningen', exact: true }).click();
    await page.getByRole('button', { name: 'Mijn oefensessies', exact: true }).click();
    await expect(page.getByLabel('BPM oefening 2 stap 1', { exact: true })).toHaveValue('80');
    await page.getByLabel('Opgeslagen oefenrondje').selectOption({ label: 'Warming-up' });
    await expect(page.getByRole('dialog')).toBeVisible();
    await page.getByRole('button', { name: 'Wijzigingen verwerpen', exact: true }).click();
    await expect(page.getByLabel('BPM oefening 1 stap 1', { exact: true })).toHaveValue('60');
    await app.close(); app = await launch(); page = await app.firstWindow();
    page.on('pageerror', reason => errors.push(reason.message));
    await page.getByRole('button', { name: 'Eigen bibliotheek bekijken' }).click();
    await page.getByLabel('Opgeslagen oefenrondje').selectOption({ label: 'Techniek' });
    await expect(page.getByLabel('BPM oefening 2 stap 1', { exact: true })).toHaveValue('75');
    await expect(page.getByLabel('BPM oefening 2 stap 2', { exact: true })).toHaveValue('95');
    await page.getByRole('button', { name: 'Stap omhoog oefening 2 stap 3', exact: true }).click();
    await expect(page.getByLabel('BPM oefening 2 stap 2', { exact: true })).toHaveValue('85');
    await page.getByRole('button', { name: 'Stap verwijderen oefening 2 stap 2', exact: true }).click();
    await expect(page.getByLabel('BPM oefening 2 stap 2', { exact: true })).toHaveValue('95');
    await page.getByRole('button', { name: 'Rondje opslaan', exact: true }).click();
    await expect(page.getByRole('status')).toContainText('opgeslagen');
    await page.setViewportSize({ width: 960, height: 700 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.getByRole('button', { name: 'Rondje verwijderen', exact: true }).click();
    await page.getByRole('dialog').getByRole('button', { name: 'Rondje verwijderen', exact: true }).click();
    await expect(page.getByLabel('Opgeslagen oefenrondje').locator('option', { hasText: 'Techniek' })).toHaveCount(0);
    expect(await page.evaluate(async () => (await window.hitthebeat!.listExercises()).length)).toBe(2);
    expect(errors).toEqual([]);
  } finally { await app.close(); await rm(data, { recursive: true, force: true }); }
});
