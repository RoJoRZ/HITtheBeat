import { test, expect, _electron as electron } from '@playwright/test';

test('example screens edit duration and expose readable player, evaluation and progress', async () => {
  const executablePath = process.env.HITTHEBEAT_TEST_EXECUTABLE;
  const desktop = await electron.launch({ executablePath, args: executablePath ? [] : ['.'], env: { ...process.env, HITTHEBEAT_DEV: '0' } });
  try {
    const page = await desktop.firstWindow();
    const errors: string[] = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.setViewportSize({ width: 1440, height: 960 });
    await expect(page.getByText('Alle oefeningen, opbouw en resultaten zijn voorbeelden. Wijzigingen worden niet opgeslagen.')).toBeVisible();
    await expect(page.getByTestId('round-duration')).toContainText('3:23');
    await page.getByRole('button', { name: 'Herhalingen stap 1 verhogen', exact: true }).click();
    await expect(page.getByTestId('round-duration')).toContainText('4:21');
    await page.getByLabel('BPM stap 1', { exact: true }).fill('10');
    await page.keyboard.press('Enter');
    await expect(page.getByRole('alert')).toContainText('23–270');
    await page.getByLabel('BPM stap 1', { exact: true }).fill('75');
    await page.keyboard.press('Enter');
    await page.getByRole('button', { name: 'Voorbeeldstap toevoegen' }).click();
    await expect(page.getByLabel('Oefening stap 5', { exact: true })).toHaveValue('akkoorden');
    await page.getByRole('button', { name: 'Stap 5 omhoog', exact: true }).click();
    await expect(page.getByLabel('Oefening stap 4', { exact: true })).toHaveValue('akkoorden');
    await page.getByRole('button', { name: 'Stap 4 verwijderen', exact: true }).click();
    await page.screenshot({ path: 'test-results/phase2-routines.png', fullPage: true });
    await page.getByRole('button', { name: 'Speelscherm bekijken' }).click();
    await expect(page.getByRole('heading', { name: 'Wisselslag', exact: true })).toBeVisible();
    await expect(page.getByRole('heading', { name: 'Opdracht', exact: true })).toBeVisible();
    await expect(page.getByRole('button', { name: 'Afspelen', exact: true })).toBeEnabled();
    await expect(page.getByRole('region', { name: 'Oefeningen in dit rondje' })).toContainText('Pentatoniek');
    await expect(page.getByText('Dagelijkse techniek · Oefening 1 van 2 · Voorbeeldweergave')).toBeVisible();
    const transport = (await page.getByRole('button', { name: 'Afspelen', exact: true }).boundingBox())!;
    expect(transport.y + transport.height).toBeLessThan(960);
    await page.getByRole('button', { name: 'Tablatuur vergroten' }).click();
    await expect(page.getByRole('dialog')).toBeVisible();
    await page.keyboard.press('Escape');
    await expect(page.getByRole('dialog')).not.toBeVisible();
    await page.screenshot({ path: 'test-results/phase2-player.png', fullPage: true });
    await page.getByRole('region', { name: 'Oefeningen in dit rondje' }).getByRole('button', { name: /2. Pentatoniek/ }).click();
    await expect(page.getByText('Dagelijkse techniek · Oefening 2 van 2 · Voorbeeldweergave')).toBeVisible();
    await expect(page.getByRole('heading', { name: 'Pentatoniek', exact: true })).toBeVisible();
    await page.getByRole('region', { name: 'Oefeningen in dit rondje' }).getByRole('button', { name: /1. Wisselslag/ }).click();
    await page.getByRole('button', { name: 'Evaluatiescherm bekijken' }).click();
    await page.getByRole('radio', { name: 'Ging goed', exact: true }).check();
    await page.getByRole('radio', { name: /Iets sneller/ }).check();
    await expect(page.getByText('80 BPM', { exact: true })).toBeVisible();
    await page.getByRole('textbox', { name: 'Een korte notitie' }).fill('De passage gaat ontspannen.');
    await page.screenshot({ path: 'test-results/phase2-evaluation.png', fullPage: true });
    await page.getByRole('button', { name: 'Voorbeeld afronden' }).click();
    await expect(page.getByRole('status')).toContainText('geen resultaten');
    await page.getByRole('button', { name: 'Bekijk het voorbeelddashboard' }).click();
    await page.getByLabel('Onderdeel', { exact: true }).selectOption('Fragment 0:12 – 0:24');
    await expect(page.getByRole('img', { name: /Voorbeeldgrafiek/ })).toHaveAttribute('aria-label', /Fragment 0:12/);
    await page.getByRole('button', { name: 'Gegevens tonen' }).click();
    await expect(page.getByRole('cell', { name: '105 BPM', exact: true })).toBeVisible();
    await page.locator('h1').click();
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: 'test-results/phase2-progress.png', fullPage: true });
    await page.getByRole('button', { name: 'Oefeningen', exact: true }).click();
    await page.getByRole('searchbox').fill('geen');
    await expect(page.getByText('Geen voorbeeld gevonden. Probeer een andere naam.')).toBeVisible();
    await page.getByRole('searchbox').fill('');
    await page.screenshot({ path: 'test-results/phase2-library.png', fullPage: true });
    await page.getByRole('button', { name: /Pentatoniek 85 BPM/ }).click();
    await page.getByRole('button', { name: 'Open de speler' }).click();
    expect(await page.locator('.assignment-scroll').evaluate(element => element.scrollHeight > element.clientHeight)).toBe(true);
    await page.setViewportSize({ width: 960, height: 700 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.getByRole('button', { name: 'Oefeningen', exact: true }).click();
    await page.getByRole('button', { name: /Akkoordwissels 70 BPM/ }).click();
    await page.getByRole('button', { name: 'Open de speler' }).click();
    await expect(page.getByRole('heading', { name: 'Opdracht', exact: true })).toBeVisible();
    await expect(page.getByRole('button', { name: 'Tablatuur vergroten' })).toHaveCount(0);
    expect(await page.locator('.practice-top').evaluate(element => getComputedStyle(element).gridTemplateColumns.split(' ').length)).toBe(1);
    await page.getByRole('button', { name: 'Mijn oefenrondjes', exact: true }).click();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    const mutedContrast = await page.evaluate(() => {
      const luminance = (hex: string) => {
        const rgb = hex.match(/[0-9a-f]{2}/gi)!.map(value => parseInt(value, 16) / 255).map(value => value <= .04045 ? value / 12.92 : ((value + .055) / 1.055) ** 2.4);
        return rgb[0] * .2126 + rgb[1] * .7152 + rgb[2] * .0722;
      };
      return (luminance('#a9b2ba') + .05) / (luminance('#23292e') + .05);
    });
    expect(mutedContrast).toBeGreaterThan(4.5);
    expect(errors).toEqual([]);
  } finally { await desktop.close(); }
});
